#!/usr/bin/env python3
"""
configure_prompt_log.py

Registers the prompt-log-hook.py Stop hook in
<project-root>/.claude/settings.json. Creates PROMPT_LOG.md at the project
root if missing. Idempotent: re-running skips work that is already done.

Usage:
  python3 configure_prompt_log.py [--project-root PATH] [--dry-run]

Default project root is the current working directory. Hook script path is
resolved relative to this script's location in the wopr-core plugin's
scripts/ directory (a sibling of hooks/).

Only Python stdlib is used.
"""

import argparse
import json
import shlex
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
HOOK_PATH = (SCRIPT_DIR.parent / "hooks" / "prompt-log-hook.py").resolve()

PROMPT_LOG_FILENAME = "PROMPT_LOG.md"

PROMPT_LOG_HEADER = """# Prompt Log

Auto-generated by the prompt-log-hook.py Stop hook. Each entry is appended
after every Claude Code response. The hook lives in the wopr-core plugin
and is registered in this project's `.claude/settings.json`.

Entry format:

```
**[YYYY-MM-DD | <8-char-session> | msg <idx>] <user prompt on one line>**
> <one-line action summary of the response>
```

To open the full transcript for any entry, find the JSONL at:

```
~/.claude/projects/<encoded-cwd>/<full-session-id>.jsonl
```

and jump to the recorded message index:

```
jq -s '.[<idx>]' ~/.claude/projects/<encoded-cwd>/<full-session-id>.jsonl
```

The 8-character session prefix in each entry matches the start of the full
session ID, so a `ls ~/.claude/projects/<encoded-cwd>/` will surface the
full filename.

---
"""


def create_prompt_log(log_path: Path, dry_run: bool) -> None:
    if log_path.exists():
        print(f"  ok       PROMPT_LOG.md already exists at {log_path}")
        return
    if dry_run:
        print(f"  [dry-run] would create PROMPT_LOG.md at {log_path}")
        return
    log_path.write_text(PROMPT_LOG_HEADER, encoding="utf-8")
    print(f"  created  PROMPT_LOG.md at {log_path}")


def register_stop_hook(settings_path: Path, hook_command: str, dry_run: bool) -> None:
    if settings_path.exists():
        try:
            settings = json.loads(settings_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            print(f"  ERROR: {settings_path} contains invalid JSON: {e}")
            print("  Fix the JSON manually before re-running this script.")
            sys.exit(1)
    else:
        settings = {}
        print(f"  note     {settings_path} does not exist; will create it")

    stop_hooks = settings.get("hooks", {}).get("Stop", [])
    for entry in stop_hooks:
        for h in entry.get("hooks", []):
            if h.get("command", "") == hook_command:
                print(f"  ok       Stop hook already registered in {settings_path}")
                return

    hooks = settings.setdefault("hooks", {})
    hooks.setdefault("Stop", []).append({
        "matcher": "",
        "hooks": [{"type": "command", "command": hook_command}],
    })

    new_text = json.dumps(settings, indent=2) + "\n"

    if dry_run:
        print(f"  [dry-run] would register Stop hook in {settings_path}")
        print(f"  [dry-run] command: {hook_command}")
        return

    settings_path.parent.mkdir(parents=True, exist_ok=True)
    settings_path.write_text(new_text, encoding="utf-8")
    print(f"  registered Stop hook in {settings_path}")
    print(f"  command: {hook_command}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path.cwd(),
        help="Project root directory (default: current working directory).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be done without making any changes.",
    )
    args = parser.parse_args()

    project_root = args.project_root.resolve()
    if not project_root.is_dir():
        sys.exit(f"ERROR: project root '{project_root}' is not a directory.")

    if not HOOK_PATH.exists():
        sys.exit(
            f"ERROR: hook script not found at {HOOK_PATH}.\n"
            "Verify the wopr-core plugin is installed correctly."
        )

    hook_command = f"python3 {shlex.quote(str(HOOK_PATH))}"
    settings_path = project_root / ".claude" / "settings.json"
    log_path = project_root / PROMPT_LOG_FILENAME

    print("=" * 60)
    print("  Configure Prompt Log")
    print("=" * 60)
    print(f"  Project root : {project_root}")
    print(f"  Hook script  : {HOOK_PATH}")
    if args.dry_run:
        print("  Dry-run      : ON; no changes will be made")
    print()

    create_prompt_log(log_path, args.dry_run)
    register_stop_hook(settings_path, hook_command, args.dry_run)

    print()
    if not args.dry_run:
        print("  Done. Restart Claude Code for the Stop hook to take effect.")
    print("=" * 60)


if __name__ == "__main__":
    main()
